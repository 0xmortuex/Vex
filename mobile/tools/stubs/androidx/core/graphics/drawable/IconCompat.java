package androidx.core.graphics.drawable;

import android.graphics.Bitmap;

public class IconCompat {
    public static IconCompat createWithBitmap(Bitmap bitmap) { return new IconCompat(); }
    public static IconCompat createWithAdaptiveBitmap(Bitmap bitmap) { return new IconCompat(); }
    public static IconCompat createWithResource(android.content.Context context, int resId) { return new IconCompat(); }
}
