#!/usr/bin/env node
// Writes src/renderer/js/tld-list.js: every top-level domain IANA lists, from
// the `tlds` package (MIT, https://github.com/stephenmathieson/node-tlds, a
// copy of https://data.iana.org/TLD/tlds-alpha-by-domain.txt), plus the names
// kept for local and private networks. The address bar uses it to tell
// "example.com" from "document.getElementById" (js/typed-address.js).
//
// Run it again to refresh the list: node scripts/gen-tld-list.js
'use strict';

const fs = require('fs');
const path = require('path');
const url = require('url');

const tlds = require('tlds');
if (!Array.isArray(tlds) || tlds.length < 1000) throw new Error('The tlds package did not give a list of top-level domains');

// Special-use and private-network names (RFC 6761, RFC 7686, RFC 8375 and
// the ones home and office networks use): a typed printer.lan, myapp.test or
// an .onion address is a place, not words.
const LOCAL = ['localhost', 'local', 'test', 'example', 'invalid', 'onion', 'lan', 'home', 'internal', 'intranet', 'corp', 'private', 'localdomain'];

const names = new Set(LOCAL);
for (const t of tlds) {
  const lower = String(t).toLowerCase();
  names.add(lower);
  const ascii = url.domainToASCII(lower);
  if (ascii && ascii !== lower) names.add(ascii);
}
const list = [...names].sort();

const out = `// Generated by scripts/gen-tld-list.js from the IANA list of top-level
// domains (via the MIT-licensed \`tlds\` package, version ${require('tlds/package.json').version}) plus local
// network names. Do not edit by hand; run the script again to refresh it.
(function () {
  const TLDS = new Set(${JSON.stringify(list)});
  if (typeof window !== 'undefined') window.VexTlds = TLDS;
  if (typeof module !== 'undefined' && module.exports) module.exports = TLDS;
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'js', 'tld-list.js'), out);
console.log('tld-list.js: ' + list.length + ' names');
