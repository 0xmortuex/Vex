#!/usr/bin/env node
// DRM / Widevine release gate (T0-021).
//
// "DRM failed" and Spotify / Disney+ / Netflix that will not play have, every
// time so far, been the same thing: the castLabs VMP (Verified Media Path)
// signature on the packaged app was invalid, or the Widevine component never
// installed (see the drm-widevine-vmp-signing note). Nothing stopped such a
// build from being uploaded; it was found by the owner, in use.
//
//   node scripts/verify-drm.js --preflight        before a release is cut: can this
//                                                 machine sign and verify at all?
//   node scripts/verify-drm.js [--dir dist/win-unpacked]
//                                                 the built app's VMP signature is
//                                                 valid, its .sig is there, and it
//                                                 is a real (not development) cert
//   node scripts/verify-drm.js --boot             the above, then start the BUILT
//                                                 Vex in a throwaway profile and
//                                                 require "Widevine ready" and a
//                                                 license request generated by the
//                                                 CDM (src/main/drm-smoke.js)
//
// `npm run publish` runs it with --boot after verify-packaged-boot and before
// anything is uploaded; scripts/release.js runs --preflight before the version
// is bumped. Exits non-zero on the first failure. A build made with
// VEX_SKIP_VMP_VERIFY=1 is a no-DRM test build and is refused here.
//
// What it cannot prove: that Google's license SERVER accepts this signature (that
// needs a real stream and a license URL). verify-pkg is castLabs' own check of
// the same signature the server looks at, and the CDM generating a request in
// the built app shows the component loads under this exe; a 403 from a license
// server is still only seen in use.
'use strict';

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const MIN_DAYS_LEFT = 30;

// run(cmd, args) -> { status, stdout, stderr, error } ; injectable for tests.
function defaultRun(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: 'utf8', windowsHide: true, timeout: opts.timeout || 120000, cwd: root, env: opts.env || process.env });
  return { status: r.status, stdout: r.stdout || '', stderr: r.stderr || '', error: r.error || null };
}
const python = process.platform === 'win32' ? 'python' : 'python3';

function refuseNoDrm(env) {
  if (env.VEX_SKIP_VMP_VERIFY === '1') {
    throw new Error('VEX_SKIP_VMP_VERIFY=1 is set: this is a no-DRM test build and is not a release artifact');
  }
}

// Can this machine sign and verify? Run before the version is bumped.
function preflight({ run = defaultRun, env = process.env } = {}) {
  refuseNoDrm(env);
  const r = run(python, ['-m', 'castlabs_evs.vmp', '--help']);
  if (r.error || r.status !== 0) {
    throw new Error('castlabs-evs is not available (' + ((r.error && r.error.message) || (r.stderr || r.stdout).trim().split('\n').pop() || 'exit ' + r.status) + '). A release without a valid VMP signature ships with broken DRM. Install it (pip install castlabs-evs) and run: python -m castlabs_evs.account reauth');
  }
  return 'castlabs-evs is available';
}

// The built app's signature.
function checkStatic({ dir, run = defaultRun, env = process.env, exists = fs.existsSync, minDays = MIN_DAYS_LEFT } = {}) {
  refuseNoDrm(env);
  if (!dir || !exists(dir)) throw new Error('there is no built app at ' + dir + ' - build first');
  const exe = path.join(dir, 'Vex.exe');
  if (!exists(exe)) throw new Error(exe + ' is missing');
  if (!exists(exe + '.sig')) throw new Error('Vex.exe.sig is missing from ' + dir + ': the app was never VMP-signed, or the signature was removed');
  const r = run(python, ['-m', 'castlabs_evs.vmp', 'verify-pkg', dir]);
  if (r.error) throw new Error('could not run castlabs-evs: ' + r.error.message);
  const out = (r.stdout + '\n' + r.stderr).trim();
  if (/valid for development only/i.test(out)) throw new Error('the signature comes from a development-only certificate; the license server will not serve a real CDM to it');
  if (r.status !== 0 || !/signature is valid/i.test(out)) {
    throw new Error('verify-pkg did not confirm the signature on ' + dir + ': ' + (out.split('\n').filter(Boolean).pop() || 'exit ' + r.status));
  }
  const m = /(\d+)\s+days?\s+left/i.exec(out);
  const days = m ? Number(m[1]) : null;
  if (days !== null && days < minDays) throw new Error('the VMP signature has only ' + days + ' days left (minimum ' + minDays + ')');
  return 'VMP signature is valid' + (days !== null ? ' (' + days + ' days left)' : '');
}

// Start the built app and require Widevine ready + a license request.
function checkBoot({ exe, run = defaultRun, env = process.env, smoke = path.join(__dirname, 'verify-smoke-boot.js') } = {}) {
  refuseNoDrm(env);
  if (!exe || !fs.existsSync(exe)) throw new Error('there is no built Vex.exe at ' + exe);
  const r = run(process.execPath, [smoke], { timeout: 300000, env: { ...env, VEX_SMOKE_EXECUTABLE: exe, VEX_DRM_SMOKE: '1', VEX_NO_OS_SCHEDULE: '1' } });
  const out = r.stdout + r.stderr;
  const m = /RESULT:\s+(PASS|FAIL)\s+—?\s*([^\n]*)/.exec(out);
  if (r.status !== 0 || !m || m[1] !== 'PASS') {
    throw new Error('the built Vex did not pass the DRM check: ' + ((m && m[2]) || out.trim().split('\n').slice(-3).join(' | ') || 'exit ' + r.status));
  }
  return m[2] || 'Widevine ready';
}

function main(argv = process.argv.slice(2), env = process.env) {
  const flag = (n) => argv.includes(n);
  const dirIdx = argv.indexOf('--dir');
  const dir = path.resolve(root, dirIdx >= 0 ? argv[dirIdx + 1] : path.join('dist', 'win-unpacked'));
  try {
    if (flag('--preflight')) { console.log('verify-drm: ' + preflight({ env })); return 0; }
    console.log('verify-drm: ' + checkStatic({ dir, env }));
    if (flag('--boot')) {
      if (env.VEX_DRM_GATE_BOOT === 'skip') {
        console.warn('verify-drm: WARNING - VEX_DRM_GATE_BOOT=skip: the built app was NOT started to check Widevine. Only the signature was checked.');
      } else {
        console.log('verify-drm: starting the built Vex to check Widevine (up to 4 minutes; the CDM is downloaded on a fresh profile) ...');
        console.log('verify-drm: ' + checkBoot({ exe: path.join(dir, 'Vex.exe'), env }));
      }
    }
    return 0;
  } catch (err) {
    console.error('verify-drm: FAILED - ' + err.message);
    console.error('verify-drm: nothing is uploaded. Fix: python -m castlabs_evs.account reauth ; python -m castlabs_evs.vmp sign-pkg -f "' + dir + '" ; verify-pkg must say "Signature is valid".');
    return 1;
  }
}

if (require.main === module) process.exit(main());

module.exports = { preflight, checkStatic, checkBoot, main, MIN_DAYS_LEFT };
