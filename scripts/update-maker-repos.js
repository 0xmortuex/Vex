#!/usr/bin/env node
// Writes src/renderer/js/maker-repos-data.js: the snapshot of the creator's PUBLIC GitHub repositories that ships
// with Vex ("More from the creator"). Owner / release-run only; users never run it. Run it before a release:
//
//   npm run update:maker
//
// Reads https://api.github.com/users/0xmortuex/repos with `gh api --paginate` when the GitHub CLI is there, else with the
// public REST API (a User-Agent, no token). Read-only. A repository that is not public is dropped (normalizeRepos in
// src/main/maker-repos.js, the same filter a refresh in the app uses), and the script throws if the file it is about to
// write holds anything that is not private:false-sourced, or looks like a token.
//
//   --out <file>   write somewhere else (tests)

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { normalizeRepos, LOGIN } = require('../src/main/maker-repos');

const OUT = path.join(__dirname, '..', 'src', 'renderer', 'js', 'maker-repos-data.js');
const MAX_BYTES = 60 * 1024;

function viaGh() {
  const out = execFileSync('gh', ['api', 'users/' + LOGIN + '/repos?per_page=100', '--paginate', '--slurp'], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] });
  const pages = JSON.parse(out);
  return pages.flat();
}

async function viaRest() {
  const all = [];
  for (let page = 1; page <= 10; page++) {
    const res = await fetch('https://api.github.com/users/' + LOGIN + '/repos?per_page=100&page=' + page, { headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'vex-update-maker-repos' }, redirect: 'error' });
    if (!res.ok) throw new Error('GitHub answered ' + res.status + (res.headers.get('x-ratelimit-reset') ? ' (limit resets at ' + new Date(Number(res.headers.get('x-ratelimit-reset')) * 1000).toISOString() + ')' : ''));
    const part = await res.json();
    if (!Array.isArray(part)) throw new Error('GitHub did not answer with a list');
    all.push(...part);
    if (part.length < 100) break;
  }
  return all;
}

async function fetchRaw() {
  try { return viaGh(); } catch (err) {
    if (err && err.code !== 'ENOENT') console.warn('gh failed (' + String(err.message).split('\n')[0] + '); using the public REST API');
    return viaRest();
  }
}

// The text of the data file for a raw API list. Pure; throws when a private repository or a secret would be written.
function buildFile(raw, now = new Date()) {
  const { repos, dropped } = normalizeRepos(raw);
  const text = JSON.stringify({ login: LOGIN, fetchedAt: now.toISOString(), repos }, null, 1);
  if (/gh[pousr]_[A-Za-z0-9]{20,}|github_pat_|"private":\s*true/.test(text)) throw new Error('The snapshot would hold something that looks like a token or a private repository; nothing was written');
  const body = '// === More from the creator: snapshot of the maker\'s PUBLIC repositories ===\n'
    + '// GENERATED by scripts/update-maker-repos.js (npm run update:maker). Do not edit by hand.\n'
    + '// Plain data, no network: the window (js/maker-repos.js) reads it; "Refresh from GitHub" is the only thing that contacts GitHub.\n'
    + 'const VexMakerReposData = ' + text + ';\n'
    + 'if (typeof window !== \'undefined\') window.VexMakerReposData = VexMakerReposData;\n'
    + 'if (typeof module !== \'undefined\' && module.exports) module.exports = { VexMakerReposData };\n';
  return { body, count: repos.length, dropped };
}

async function main() {
  const i = process.argv.indexOf('--out');
  const out = i > 0 ? path.resolve(process.argv[i + 1]) : OUT;
  const { body, count, dropped } = buildFile(await fetchRaw());
  if (Buffer.byteLength(body) > MAX_BYTES) throw new Error('The snapshot is ' + Buffer.byteLength(body) + ' bytes, over the ' + MAX_BYTES + ' byte limit; trim fields in normalizeRepos');
  fs.writeFileSync(out, body, 'utf8');
  console.log('Wrote ' + count + ' public repositories (' + dropped + ' dropped as not public) to ' + path.relative(process.cwd(), out) + ' (' + Buffer.byteLength(body) + ' bytes)');
}

if (require.main === module) main().catch((err) => { console.error(err.message); process.exit(1); });
module.exports = { buildFile };
