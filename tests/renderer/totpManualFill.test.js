// @vitest-environment jsdom
// @vitest-environment-options { "url": "https://www.roblox.com/communities/configure?id=1" }
// "Fill code from authenticator": the right-click row, Ctrl+K and what they do.
// The owner's report (2026-10-12): the page's menu had "Fill code from email"
// but no authenticator entry, so a code the automatic pass missed could not be
// asked for.
import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { TotpAutofill } from '../../src/renderer/js/totp-autofill.js';

const wait = (ms) => new Promise(r => setTimeout(r, ms));
const sized = () => { Element.prototype.getBoundingClientRect = function () { return { width: 120, height: 30, top: 0, left: 0, right: 120, bottom: 30 }; }; };
const guest = (href = 'https://www.roblox.com/communities/configure?id=1') => ({
  isConnected: true,
  getURL: () => href,
  executeJavaScript: (js) => Promise.resolve(window.eval(js)),
});

describe('Fill code from authenticator', () => {
  let toasts;
  beforeEach(() => {
    sized();
    localStorage.clear();
    delete window.VexTabPolicy;
    toasts = [];
    window.showToast = (m, k) => toasts.push([m, k]);
    TotpAutofill.forgetAccounts();
    document.body.innerHTML = '<div role="dialog"><p>Enter the code generated by your authenticator app.</p><input id="otp" placeholder="Enter 6-digit Code"><input id="other" placeholder="Nickname"></div>';
    window.vex = {
      totpList: vi.fn(async () => [{ id: 'r', issuer: '', label: 'Roblox' }, { id: 'g', issuer: 'GitHub', label: 'me' }]),
      totpCodes: vi.fn(async () => [{ id: 'r', code: '111111' }, { id: 'g', code: '222222' }]),
    };
  });
  afterEach(() => { document.getElementById('vex-totp-pick')?.remove(); });

  it('fills the code field with the account of this site, with no extra question', async () => {
    const r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r.ok).toBe(true);
    expect(document.getElementById('otp').value).toBe('111111');
    expect(document.getElementById('other').value).toBe('');
    expect(toasts[0][0]).toMatch(/Authenticator code filled/);
  });

  it('fills the field the person has focused, even when it does not look like a code field', async () => {
    document.getElementById('other').focus();
    const r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r.ok).toBe(true);
    expect(document.getElementById('other').value).toBe('111111');
    expect(document.getElementById('otp').value).toBe('');
  });

  it('never types into a password field', async () => {
    document.body.innerHTML = '<input id="pw" type="password">';
    document.getElementById('pw').focus();
    const r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r.ok).toBe(false);
    expect(document.getElementById('pw').value).toBe('');
    expect(toasts[0][0]).toMatch(/No code field/);
  });

  it('asks which account when several belong to the site', async () => {
    window.vex.totpList = async () => [{ id: 'r', issuer: '', label: 'Roblox' }, { id: 'r2', issuer: 'Roblox', label: 'alt' }];
    window.vex.totpCodes = async () => [{ id: 'r', code: '111111' }, { id: 'r2', code: '333333' }];
    const pending = TotpAutofill.fillFromAuthenticator(guest());
    await wait(30);
    const picker = document.getElementById('vex-totp-pick');
    expect(picker).toBeTruthy();
    [...picker.querySelectorAll('[data-list] button')].find(b => /alt/.test(b.textContent)).click();
    const r = await pending;
    expect(r.ok).toBe(true);
    expect(document.getElementById('otp').value).toBe('333333');
  });

  it('when no account belongs to the site, says so and lets the person pick any account, then remembers it', async () => {
    window.vex.totpList = async () => [{ id: 'g', issuer: 'GitHub', label: 'me' }, { id: 'm', issuer: 'MyBank', label: 'bank' }];
    window.vex.totpCodes = async () => [{ id: 'g', code: '222222' }, { id: 'm', code: '444444' }];
    const pending = TotpAutofill.fillFromAuthenticator(guest());
    await wait(30);
    const picker = document.getElementById('vex-totp-pick');
    expect(picker.querySelector('#vex-totp-pick-title').textContent).toMatch(/No authenticator account for this site/);
    expect(picker.querySelector('[data-host]').textContent).toMatch(/roblox\.com/);
    const names = [...picker.querySelectorAll('[data-list] button')].map(b => b.textContent);
    expect(names).toEqual(['GitHub · me', 'MyBank · bank']);   // ALL accounts
    [...picker.querySelectorAll('[data-list] button')][1].click();
    const r = await pending;
    expect(r.ok).toBe(true);
    expect(document.getElementById('otp').value).toBe('444444');
    // The site is now that account's: the automatic fill matches it.
    expect(TotpAutofill._matchKind({ id: 'm', issuer: 'MyBank', label: 'bank' }, 'roblox.com')).toBe('bound');
  });

  it('a dismissed picker fills nothing', async () => {
    window.vex.totpList = async () => [{ id: 'g', issuer: 'GitHub', label: 'me' }];
    const pending = TotpAutofill.fillFromAuthenticator(guest());
    await wait(30);
    document.querySelector('#vex-totp-pick [data-cancel]').click();
    const r = await pending;
    expect(r).toEqual({ ok: false, reason: 'cancelled' });
    expect(document.getElementById('otp').value).toBe('');
    expect(window.vex.totpCodes).not.toHaveBeenCalled();
  });

  it('refuses in a private or Tor tab, before reading anything', async () => {
    window.VexTabPolicy = { canFillWebview: () => false };
    const r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r).toEqual({ ok: false, reason: 'private' });
    expect(window.vex.totpList).not.toHaveBeenCalled();
    expect(toasts[0][0]).toMatch(/private or Tor/);
  });

  it('refuses a page that is not https', async () => {
    const r = await TotpAutofill.fillFromAuthenticator(guest('http://www.roblox.com/'));
    expect(r.reason).toBe('not-https');
    expect(window.vex.totpList).not.toHaveBeenCalled();
  });

  it('says so when Vex is locked, and when there are no accounts', async () => {
    window.vex.totpList = async () => { throw new Error('Vex is locked — unlock it first'); };
    let r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r.reason).toBe('locked');
    expect(toasts.pop()[0]).toMatch(/locked/);
    window.vex.totpList = async () => [];
    r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r.reason).toBe('no-accounts');
    expect(toasts.pop()[0]).toMatch(/No authenticator accounts yet/);
  });

  it('says so when the page has no code field at all', async () => {
    document.body.innerHTML = '<p>Nothing here</p>';
    const r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r.reason).toBe('no-field');
    expect(toasts[0][0]).toMatch(/No code field/);
  });

  it('does not fill into a page that has moved to another origin while the code was read', async () => {
    const wv = guest();
    let moved = false;
    wv.getURL = () => (moved ? 'https://evil.test/' : 'https://www.roblox.com/communities/configure?id=1');
    window.vex.totpCodes = async () => { moved = true; return [{ id: 'r', code: '111111' }]; };
    const r = await TotpAutofill.fillFromAuthenticator(wv);
    expect(r.ok).toBe(false);
    expect(document.getElementById('otp').value).toBe('');
  });
});

describe('when the menu row shows', () => {
  const wv = (href) => ({ getURL: () => href, getAttribute: () => 'persist:main' });
  beforeEach(() => { delete window.VexTabPolicy; TotpAutofill.forgetAccounts(); });
  it('shows on an input while the account list is not known yet, hides when it is known empty', () => {
    expect(TotpAutofill.shouldOfferMenuRow(wv('https://www.roblox.com/'), true)).toBe(true);
    expect(TotpAutofill.shouldOfferMenuRow(wv('https://www.roblox.com/'), false)).toBe(false);
    TotpAutofill._noteAccounts([]);
    expect(TotpAutofill.shouldOfferMenuRow(wv('https://www.roblox.com/'), true)).toBe(false);
  });
  it('shows on a non-input only where an account belongs to the site', () => {
    TotpAutofill._noteAccounts([{ id: 'r', issuer: '', label: 'Roblox' }]);
    expect(TotpAutofill.shouldOfferMenuRow(wv('https://www.roblox.com/x'), false)).toBe(true);
    expect(TotpAutofill.shouldOfferMenuRow(wv('https://www.example.com/x'), false)).toBe(false);
    expect(TotpAutofill.shouldOfferMenuRow(wv('https://www.example.com/x'), true)).toBe(true);
  });
  it('never shows in a private tab or on an http page', () => {
    TotpAutofill._noteAccounts([{ id: 'r', issuer: '', label: 'Roblox' }]);
    expect(TotpAutofill.shouldOfferMenuRow(wv('http://www.roblox.com/'), true)).toBe(false);
    window.VexTabPolicy = { canFillWebview: () => false };
    expect(TotpAutofill.shouldOfferMenuRow(wv('https://www.roblox.com/'), true)).toBe(false);
  });
});

describe('wiring', () => {
  const read = (p) => fs.readFileSync(path.join(__dirname, '../../src/renderer/js', p), 'utf8');
  it('the page menu and Ctrl+K both offer it, next to Fill code from email', () => {
    expect(read('webview.js')).toMatch(/TotpAutofill\.fillFromAuthenticator\(webview/);
    expect(read('webview.js')).toMatch(/menuFillTotp/);
    expect(read('command.js')).toMatch(/id: 'filltotp', label: 'Fill code from authenticator'/);
  });
  it('has Turkish for every string it can say', () => {
    const src = read('i18n.js');
    for (const key of ['menuFillTotp', 'totpNoAccounts', 'totpNoneHere', 'totpNoField', 'totpPrivate', 'totpLocked', 'totpFilled']) {
      const hits = src.match(new RegExp('\\b' + key + ':', 'g')) || [];
      expect(hits.length, key).toBeGreaterThanOrEqual(2);   // en and tr
    }
  });
});
