// @vitest-environment jsdom
// @vitest-environment-options { "url": "https://www.roblox.com/communities/configure?id=1" }
// T3-114 (Wave 6): while the screen is shared and the person ticked "Also hold the passkey chooser, 2FA codes,
// emailed codes and the AI sign-in while sharing", none of those is filled or offered, and the agent is told.
import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { TotpAutofill } from '../../src/renderer/js/totp-autofill.js';
import { VexShareHold as H } from '../../src/renderer/js/share-hold.js';

const src = (p) => fs.readFileSync(path.join(__dirname, '../../src/renderer/js', p), 'utf8');
const guest = (href = 'https://www.roblox.com/communities/configure?id=1') => ({
  isConnected: true, getURL: () => href, _navigationGeneration: 1,
  executeJavaScript: (js) => Promise.resolve(window.eval(js)),
});

// A stand-in for Screen-share safe mode: the same two calls the real one answers (active, noteHeld).
function safeMode() {
  const s = { on: false, held: 0, active: () => s.on, noteHeld: () => ++s.held };
  return s;
}
let safe, toasts;

beforeEach(() => {
  Element.prototype.getBoundingClientRect = function () { return { width: 120, height: 30, top: 0, left: 0, right: 120, bottom: 30 }; };
  localStorage.clear();
  document.body.innerHTML = '<div role="dialog"><p>Enter the code generated by your authenticator app.</p><input id="otp" placeholder="Enter 6-digit Code"></div>';
  delete window.VexTabPolicy;
  toasts = [];
  window.showToast = (...a) => toasts.push(a);
  safe = safeMode();
  globalThis.VexScreenShareSafe = safe;
  globalThis.VexShareHold = H;
  H._held = new Set();
  TotpAutofill.forgetAccounts();
  window.vex = {
    totpList: vi.fn(async () => [{ id: 'r', issuer: '', label: 'Roblox' }]),
    totpCodes: vi.fn(async () => [{ id: 'r', code: '111111' }]),
  };
});
afterEach(() => { delete globalThis.VexScreenShareSafe; delete globalThis.VexShareHold; });

describe('the switch', () => {
  it('is off until ticked, and holds nothing without a share', () => {
    expect(H.enabled()).toBe(false);
    safe.on = true;
    expect(H.holds('totp')).toBe(false);
    H.setEnabled(true);
    expect(H.holds('totp')).toBe(true);
    safe.on = false;
    expect(H.holds('totp')).toBe(false);
  });
  it('counts each kind once on the safe-mode pill, and lifts when safe mode is not in force (off for this share)', () => {
    H.setEnabled(true);
    safe.on = true;
    H.holds('totp'); H.holds('totp'); H.holds('passkey');
    expect(safe.held).toBe(2);
    expect(H.heldKinds().sort()).toEqual(['2FA codes', 'the passkey chooser']);
    safe.on = false;                                         // paused for this share, or the share ended
    expect(H.holds('passkey')).toBe(false);
    expect(H.heldKinds()).toEqual([]);
  });
  it('refuses an unknown kind and works without safe mode being loaded', () => {
    expect(() => H.holds('nope')).toThrow(/unknown kind/);
    delete globalThis.VexScreenShareSafe;
    H.setEnabled(true);
    expect(H.holds('totp')).toBe(false);
  });
});

describe('the fills', () => {
  it('a 2FA code is not filled from the authenticator while held, and is when the share ends', async () => {
    H.setEnabled(true);
    safe.on = true;
    const r = await TotpAutofill.fillFromAuthenticator(guest());
    expect(r).toEqual({ ok: false, reason: 'share-safe' });
    expect(window.vex.totpCodes).not.toHaveBeenCalled();
    expect(document.getElementById('otp').value).toBe('');
    expect(toasts.some(t => /Held while your screen is shared/.test(t[0]))).toBe(true);
    safe.on = false;
    const again = await TotpAutofill.fillFromAuthenticator(guest());
    expect(again.ok).toBe(true);
    expect(document.getElementById('otp').value).toBe('111111');
  });

  it('the hold sits on the passkey chooser, the emailed code and the AI sign-in as well', () => {
    expect(src('passkeys.js')).toMatch(/e\.channel === 'vex-passkey-field' && typeof VexShareHold !== 'undefined' && VexShareHold\.holds\('passkey'\)/);
    expect(src('email-code-autofill.js').match(/VexShareHold\.holds\('emailcode'\)/g)).toHaveLength(2);
    expect(src('agent-executor.js')).toMatch(/VexShareHold\.holds\('agent'\)\) return \{ ok: false, error: '[^']*hand_over/);
    expect(src('totp-autofill.js').match(/VexShareHold\.holds\('totp'\)/g)).toHaveLength(3);
  });

  it('is wired: a script tag, the settings row and the manifest key', () => {
    const html = fs.readFileSync(path.join(__dirname, '../../src/renderer/index.html'), 'utf8');
    expect(html).toMatch(/<script src="js\/share-hold\.js"><\/script>/);
    expect(src('security-helpers.js')).toMatch(/VexShareHold\.setEnabled/);
    expect(src('feature-manifests.js')).toMatch(/'vex\.shareSafe', 'vex\.shareHold'/);
  });
});
