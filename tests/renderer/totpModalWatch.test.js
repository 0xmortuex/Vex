// @vitest-environment jsdom
// @vitest-environment-options { "url": "https://www.roblox.com/communities/configure?id=1" }
// Found 2026-10-12 (owner's report, Roblox): "autofill for authenticator didn't
// work". Roblox opens "2-Step Verification" as a modal in the middle of a
// logged-in session (changing a group's owner), on the same address, with no
// page load. TotpAutofill looked once at load, saw no password box and no 2FA
// wording, and gave up for good, so the modal's field was never even looked at.
// Now such a page is watched for a field appearing, and the field detector
// reads the label, the words around the field and shadow roots.
import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import { TotpAutofill } from '../../src/renderer/js/totp-autofill.js';

const wait = (ms) => new Promise(r => setTimeout(r, ms));
const sized = () => { Element.prototype.getBoundingClientRect = function () { return { width: 120, height: 30, top: 0, left: 0, right: 120, bottom: 30 }; }; };

function guest(href = 'https://www.roblox.com/communities/configure?id=1#!/members') {
  const state = { href };
  return {
    isConnected: true,
    getURL: () => state.href,
    executeJavaScript: (js) => Promise.resolve(window.eval(js)),
  };
}

const MODAL = '<div role="dialog" aria-modal="true"><h4>2-Step Verification</h4><p>Enter the code generated by your authenticator app.</p><input id="otp" type="text" placeholder="Enter 6-digit Code"><button>Verify</button></div>';

describe('a 2FA modal that opens on a logged-in page', () => {
  let activation;
  const realSetInterval = window.setInterval;
  beforeEach(() => {
    sized();
    // The injected filler's short retry (every 400 ms) is not what is tested here.
    window.setInterval = () => 0;
    delete window.VexTabPolicy;
    document.body.innerHTML = '<div id="app"><h1>Configure Community</h1><input type="search" placeholder="Search members"></div><div id="portal"></div>';
    activation = { isActive: true };
    Object.defineProperty(navigator, 'userActivation', { configurable: true, get: () => activation });
    localStorage.clear();
    window.vexConfirm = vi.fn(async () => true);
    window.vex = {
      totpList: async () => [{ id: 'r', issuer: '', label: 'Roblox' }],
      totpCodes: vi.fn(async () => [{ id: 'r', code: '246810' }]),
    };
  });
  // The watcher's marker lives on the (shared) jsdom document: drop it so each
  // test starts a fresh watcher, as a fresh page would.
  // A watcher ends when its marker is gone and the page changes; a finished
  // one re-arms a moment later, so do it twice.
  // Each fill also leaves a click-to-refill listener on the shared jsdom
  // document: answer those with no code to give, so they do not fire in the
  // next test.
  afterEach(async () => {
    window.vex = { totpList: async () => [], totpCodes: async () => [] };
    for (let i = 0; i < 3; i++) {
      delete document[Symbol.for('vex.totp.watch')];
      document.body.innerHTML = '<p>Enter the code from your authenticator app</p><input id="drain" autocomplete="one-time-code"><input id="drain-other">';
      document.getElementById('drain-other').focus();
      document.getElementById('drain').focus();
      await wait(250);
    }
    document.body.innerHTML = '';
    window.setInterval = realSetInterval;
    delete navigator.userActivation;
  });

  it('fills the code when the modal appears after the page loaded', async () => {
    const wv = guest();
    await TotpAutofill.autofill(wv, wv.getURL());       // load: nothing to fill yet, and it returns at once
    expect(window.vex.totpCodes).not.toHaveBeenCalled();
    await wait(300);
    document.getElementById('portal').innerHTML = MODAL; // the modal renders into a portal
    await wait(1100);
    expect(window.vexConfirm).toHaveBeenCalledTimes(1);  // first time for this site: asks once
    expect(document.getElementById('otp').value).toBe('246810');
  });

  it('fills a modal whose field only carries a label, or only nearby words', async () => {
    const wv = guest();
    await TotpAutofill.autofill(wv, wv.getURL());
    await wait(300);
    document.getElementById('portal').innerHTML = '<div role="dialog"><label for="c1">Verification code</label><input id="c1" type="text" name="c1"></div>';
    await wait(1100);
    expect(document.getElementById('c1').value).toBe('246810');
  });

  it('does not fill when no account matches the site', async () => {
    window.vex.totpList = async () => [{ id: 'g', issuer: 'GitHub', label: 'me' }];
    const wv = guest();
    await TotpAutofill.autofill(wv, wv.getURL());
    await wait(300);
    document.getElementById('portal').innerHTML = MODAL;
    await wait(1100);
    expect(window.vex.totpCodes).not.toHaveBeenCalled();
    expect(document.getElementById('otp').value).toBe('');
  });

  it('is not fooled by a promo box or a search box appearing', async () => {
    const wv = guest();
    await TotpAutofill.autofill(wv, wv.getURL());
    await wait(300);
    document.getElementById('portal').innerHTML = '<div role="dialog"><p>Have a promo code?</p><input id="promo" type="text" placeholder="Code"></div>';
    await wait(1100);
    expect(window.vex.totpCodes).not.toHaveBeenCalled();
    expect(document.getElementById('promo').value).toBe('');
  });

  it('watches the page once, even when autofill runs again for an in-page route change', async () => {
    const wv = guest();
    await TotpAutofill.autofill(wv, wv.getURL());
    await TotpAutofill.autofill(wv, wv.getURL() + 'x');
    await wait(300);
    document.getElementById('portal').innerHTML = MODAL;
    await wait(1100);
    expect(window.vexConfirm).toHaveBeenCalledTimes(1);
    expect(window.vex.totpCodes).toHaveBeenCalledTimes(1);
  });

  it('fills the next modal too, after the first one closed', async () => {
    window.vexConfirm = vi.fn(async () => true);
    const wv = guest();
    await TotpAutofill.autofill(wv, wv.getURL());
    await wait(300);
    document.getElementById('portal').innerHTML = MODAL;
    await wait(1100);
    expect(document.getElementById('otp').value).toBe('246810');
    document.getElementById('portal').innerHTML = '';
    await wait(300);
    document.getElementById('portal').innerHTML = MODAL;
    await wait(1100);
    expect(document.getElementById('otp').value).toBe('246810');
    expect(window.vex.totpCodes.mock.calls.length).toBeGreaterThanOrEqual(2);
  });

  it('a page script that merely focuses the field is not a click', async () => {
    // Field already on the page when watching starts (so "appeared" cannot fire).
    document.getElementById('portal').innerHTML = MODAL;
    const wv = guest();
    window.vex.totpList = async () => [{ id: 'r', issuer: '', label: 'Roblox' }];
    TotpAutofill._bind({ id: 'r', issuer: '', label: 'Roblox' }, 'roblox.com', true);
    TotpAutofill._watch(wv, wv.getURL(), 'roblox.com');
    await wait(300);
    activation.isActive = false;
    document.getElementById('otp').dispatchEvent(new FocusEvent('focusin', { bubbles: true }));
    await wait(300);
    expect(window.vex.totpCodes).not.toHaveBeenCalled();
  });
});

describe('what counts as a one-time-code field', () => {
  beforeEach(() => { sized(); delete window.VexTabPolicy; });
  const detect = (html) => {
    document.body.innerHTML = html;
    // eslint-disable-next-line no-new-func
    const D = new Function('return (' + TotpAutofill._detectorSource() + ')();')();
    return D.fields().single.map(el => el.id);
  };
  it('reads placeholder, label, aria-label and nearby words', () => {
    expect(detect('<input id="a" placeholder="Enter 6-digit Code">')).toEqual(['a']);
    expect(detect('<label for="b">Authenticator code</label><input id="b">')).toEqual(['b']);
    expect(detect('<input id="c" aria-label="Verification code">')).toEqual(['c']);
    expect(detect('<div><span>Enter the code from your authenticator app</span><input id="d" placeholder="000000"></div>')).toEqual(['d']);
  });
  it('ignores promo, search, email and password fields, and a hidden field', () => {
    expect(detect('<input id="a" placeholder="Promo code"><input id="b" type="search" placeholder="Search"><input id="c" type="password" placeholder="Code"><input id="d" type="email" placeholder="Email"><input id="e" placeholder="Code" style="display:none">')).toEqual([]);
  });
  it('finds a field inside an open shadow root', () => {
    document.body.innerHTML = '<div id="host"></div>';
    const root = document.getElementById('host').attachShadow({ mode: 'open' });
    root.innerHTML = '<input id="s" autocomplete="one-time-code">';
    const D = new Function('return (' + TotpAutofill._detectorSource() + ')();')();
    expect(D.fields().single.map(e => e.id)).toEqual(['s']);
  });
  it('skips a field in an inert region', () => {
    expect(detect('<div inert><input id="a" autocomplete="one-time-code"></div>')).toEqual([]);
  });
});

describe('a site the person set for an account', () => {
  it('matches whatever the host is called once bound', () => {
    localStorage.clear();
    const account = { id: 'x', issuer: 'MyBank', label: 'me' };
    expect(TotpAutofill._matchKind(account, 'secure.example.net')).toBeNull();
    TotpAutofill._bind(account, 'secure.example.net', true);
    expect(TotpAutofill._matchKind(account, 'secure.example.net')).toBe('bound');
    TotpAutofill._bind(account, 'secure.example.net', false);
    expect(TotpAutofill._matchKind(account, 'secure.example.net')).toBeNull();
  });
});
